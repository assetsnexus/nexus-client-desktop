/**
 * Per-locale blocks: the English block with the locale's overrides merged on
 * top, so every locale exposes exactly the English key set (a missing override
 * simply falls back to English) and placeholders never drift.
 */
export const STORAGE_LOCALE_MESSAGES: Record<Locale, Record<string, string>> = (() => {
  const locales: Locale[] = [
    'en',
    'de',
    'es',
    'fr',
    'ru',
    'uk',
    'et',
    'it',
    'pt',
    'nl',
    'pl',
    'tr',
    'ar',
    'hi',
    'zh',
    'ja',
    'ko',
  ];
  const out = {} as Record<Locale, Record<string, string>>;
  for (const locale of locales) {
    out[locale] = { ...EN, ...(OVERRIDES[locale] ?? {}) };
  }
  return out;
})();
