/**
 * Storage-hub UI translations.
 *
 * The unified Storage surface (browse / mounts / sync / agent folders / access)
 * used to be three ad-hoc panels with hardcoded English. Restructuring it into a
 * Settings-like hub made the copy visible again, so it lives here, in one module,
 * mirroring `locales-settings.ts`.
 *
 * Keys are part of the English source dictionary (`locales.ts` declares the
 * English values); `locales.ts` merges these per-locale blocks into
 * `DICTIONARIES` so the i18n registry invariants hold (every locale covers every
 * English key, placeholders intact).
 *
 * COPY NOTES:
 *  - Product names stay as-is (`Nexus`).
 *  - `{name}` placeholders are interpolated by `translate()`; keep them intact.
 *  - A locale without a dedicated block falls back to the English strings, so a
 *    partially translated locale never shows raw keys.
 */

